import { render, screen, waitFor, within, act } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { AppRoutes } from '../App'
import AuthProvider from '../auth/AuthProvider'
import authService from '../auth/authService'
import workOrderService from '../workOrders/workOrderService'
import operationsService from './operationsService'
import inventoryService from './inventoryService'
import { inventoryMeta, inventoryMaterial, movement, preview } from './inventoryFixtures'
import { collection, user, flow, consumption, httpError } from './operationsFixtures'
import { order } from '../workOrders/workOrderFixtures'
vi.mock('../auth/authService', () => ({ default: { currentUser: vi.fn(), logout: vi.fn() } }))
vi.mock('../workOrders/workOrderService', () => ({ default: { get: vi.fn(), meta: vi.fn() } }))
vi.mock('./inventoryService', () => ({ default: { meta: vi.fn(), stock: vi.fn(), preview: vi.fn(), movements: vi.fn(), movement: vi.fn(), confirm: vi.fn(), dashboard: vi.fn() } }))
vi.mock('./operationsService', () => ({ default: { catalog: vi.fn(), saveCatalog: vi.fn(), flow: vi.fn(), consumptions: vi.fn(), inspections: vi.fn(), consume: vi.fn() } }))
function renderApp(path) { return render(<MemoryRouter initialEntries={[path]}><AuthProvider><AppRoutes /></AuthProvider></MemoryRouter>) }
beforeEach(() => {
  vi.resetAllMocks()
  authService.currentUser.mockResolvedValue(user)
  inventoryService.meta.mockResolvedValue(structuredClone(inventoryMeta))
  inventoryService.stock.mockResolvedValue(inventoryMaterial)
  inventoryService.preview.mockResolvedValue(preview)
  inventoryService.movements.mockResolvedValue(collection([movement]))
  inventoryService.movement.mockResolvedValue(movement)
  inventoryService.confirm.mockResolvedValue(movement)
  inventoryService.dashboard.mockResolvedValue({ indicators: { total_components: 8, critical: 2, reorder: 1, ok: 3, overstock: 1, no_parameters: 1 }, alerts: collection([inventoryMaterial]) })
  operationsService.catalog.mockResolvedValue(collection([inventoryMaterial]))
  operationsService.saveCatalog.mockResolvedValue(inventoryMaterial)
  operationsService.flow.mockResolvedValue(flow)
  operationsService.consumptions.mockResolvedValue(collection([]))
  operationsService.inspections.mockResolvedValue(collection([]))
  operationsService.consume.mockResolvedValue({ ...consumption, inventory_movement: movement })
  workOrderService.get.mockResolvedValue(structuredClone(order))
})
async function prepareMovement(clicker) {
  renderApp('/materials/movements/new?material_id=5')
  await clicker.selectOptions(await screen.findByLabelText('Tipo de movimiento'), 'exit')
  await clicker.type(screen.getByLabelText('Cantidad original'), '750')
  await clicker.selectOptions(screen.getByLabelText('Unidad del movimiento'), 'ml')
  await waitFor(() => expect(screen.getByLabelText('Cantidad equivalente')).toHaveValue('0.750000'))
}
describe('inventory screens', () => {
  it('shows calculated stock, parameters, visible status and location', async () => {
    renderApp('/materials')
    expect(await screen.findByText('5.000000')).toBeInTheDocument()
    for (const text of ['6.000000', '10.000000', '50.00%', 'Laboratorio de Pintura', 'Proveedor de prueba']) expect(screen.getByText(text)).toBeInTheDocument()
    expect(screen.getByRole('navigation', { name: 'Navegación de materiales' })).toBeInTheDocument()
    expect(screen.getByText('Stock inicial')).toBeInTheDocument()
    expect(screen.getByText('Ajustes negativos')).toBeInTheDocument()
    expect(screen.getByText('5.000000 L')).toBeInTheDocument()
  })
  it('filters inventory status on the server', async () => {
    const clicker = userEvent.setup()
    renderApp('/materials')
    await clicker.selectOptions(await screen.findByLabelText('Estado de inventario'), 'critical')
    await clicker.click(screen.getByRole('button', { name: 'Buscar' }))
    await waitFor(() => expect(operationsService.catalog).toHaveBeenLastCalledWith('materials', expect.objectContaining({ stock_status: 'critical' }), expect.anything()))
  })
  it('edits min/max and locks the canonical unit after history', async () => {
    const clicker = userEvent.setup()
    renderApp('/materials')
    await clicker.click(await screen.findByRole('button', { name: 'Editar ' + inventoryMaterial.name }))
    expect(screen.getByRole('combobox', { name: 'Unidad de medida' })).toBeDisabled()
    expect(screen.queryByLabelText('Stock actual')).not.toBeInTheDocument()
    await clicker.clear(screen.getByLabelText('Stock mínimo'))
    await clicker.type(screen.getByLabelText('Stock mínimo'), '7.5')
    await clicker.click(screen.getByRole('button', { name: 'Guardar registro' }))
    await waitFor(() => expect(operationsService.saveCatalog).toHaveBeenCalledWith('materials', 5, expect.objectContaining({ minimum_stock: '7.5', unit: 'L' })))
  })
  it('shows all dashboard indicators, alert actions and refreshes after mutation', async () => {
    renderApp('/materials/inventory/dashboard')
    expect(await screen.findByText('COMPRAR / REABASTECER')).toBeInTheDocument()
    const indicators = screen.getByText('Total componentes').closest('div')
    expect(within(indicators).getByText('8')).toBeInTheDocument()
    expect(within(indicators).getByText('CRÍTICO').closest('article')).toHaveTextContent('2')
    expect(within(indicators).getByText('SOBRESTOCK')).toBeInTheDocument()
    await act(async () => window.dispatchEvent(new Event('inventory-changed')))
    await waitFor(() => expect(inventoryService.dashboard).toHaveBeenCalledTimes(2))
  })
  it('handles an empty alert list', async () => {
    inventoryService.dashboard.mockResolvedValue({ indicators: {}, alerts: collection([]) })
    renderApp('/materials/inventory/dashboard')
    expect(await screen.findByText('No hay alertas de inventario.')).toBeInTheDocument()
  })
  it('lists original and equivalent quantities with server folio and actor', async () => {
    renderApp('/materials/movements')
    const table = await screen.findByRole('table')
    expect(within(table).getByRole('link', { name: movement.folio })).toHaveAttribute('href', '/materials/movements/10')
    for (const text of ['750.000000', 'ml', '0.750000 L', 'Admin de prueba', 'Pintura 1']) expect(within(table).getByText(text)).toBeInTheDocument()
  })
  it('filters movements by date, type and destination with server pagination', async () => {
    inventoryService.movements.mockResolvedValue(collection([movement], { current_page: 1, last_page: 2, total: 25 }))
    const clicker = userEvent.setup()
    renderApp('/materials/movements')
    await clicker.selectOptions(await screen.findByLabelText('Tipo de movimiento'), 'exit')
    await clicker.selectOptions(screen.getByLabelText('Área / destino'), 'Lavado')
    await clicker.type(screen.getByLabelText('Desde'), '2026-11-01')
    await clicker.click(screen.getByRole('button', { name: 'Aplicar filtros' }))
    await waitFor(() => expect(inventoryService.movements).toHaveBeenLastCalledWith(expect.objectContaining({ movement_type: 'exit', area_destination: 'Lavado', date_from: '2026-11-01' }), expect.anything()))
    await clicker.click(within(screen.getByRole('navigation', { name: 'Paginación de movimientos' })).getByRole('button', { name: 'Siguiente' }))
    await waitFor(() => expect(inventoryService.movements).toHaveBeenLastCalledWith(expect.objectContaining({ page: '2', movement_type: 'exit' }), expect.anything()))
  })
  it('shows a confirmed movement as read-only', async () => {
    renderApp('/materials/movements/10')
    expect(await screen.findByText('LDR-DP-0001')).toBeInTheDocument()
    expect(screen.getByText('Aplicado en cabina')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: /Editar|Eliminar/ })).not.toBeInTheDocument()
  })
  it('handles loading, empty and network retry', async () => {
    inventoryService.movements.mockReturnValue(new Promise(() => {}))
    const view = renderApp('/materials/movements')
    expect(await screen.findByText('Cargando información…')).toBeInTheDocument()
    view.unmount()
    inventoryService.movements.mockRejectedValueOnce(new Error('network')).mockResolvedValue(collection([]))
    renderApp('/materials/movements')
    const clicker = userEvent.setup()
    await clicker.click(await screen.findByRole('button', { name: 'Reintentar' }))
    expect(await screen.findByText('No hay movimientos para mostrar.')).toBeInTheDocument()
  })
})
describe('movement confirmation', () => {
  it('uses backend preview, read-only equivalence and server receipt', async () => {
    const clicker = userEvent.setup()
    await prepareMovement(clicker)
    expect(screen.getByLabelText('Cantidad equivalente')).toHaveAttribute('readonly')
    expect(screen.getByLabelText('Cantidad equivalente').tagName).toBe('INPUT')
    await waitFor(() => expect(inventoryService.preview).toHaveBeenLastCalledWith(5, { quantity_original: '750', unit_original: 'ml', movement_type: 'exit' }, expect.anything()))
    await clicker.click(screen.getByRole('button', { name: 'Confirmar movimiento' }))
    expect(await screen.findByText('LDR-DP-0001')).toBeInTheDocument()
    expect(screen.getByText('4.250000')).toBeInTheDocument()
    expect(inventoryService.confirm).toHaveBeenCalledWith(expect.objectContaining({ material_id: 5, quantity_original: '750', unit_original: 'ml', idempotency_key: expect.any(String) }))
  })
  it('blocks insufficient stock without calling confirmation', async () => {
    inventoryService.preview.mockResolvedValue({ ...preview, can_confirm: false, sufficient_stock: false, stock_after: '-1.000000' })
    const clicker = userEvent.setup()
    await prepareMovement(clicker)
    expect(screen.getByRole('button', { name: 'Confirmar movimiento' })).toBeDisabled()
    expect(screen.getByRole('alert')).toHaveTextContent(/insuficiente/i)
    expect(inventoryService.confirm).not.toHaveBeenCalled()
  })
  it('requires justification for adjustments', async () => {
    const clicker = userEvent.setup()
    await prepareMovement(clicker)
    await clicker.selectOptions(screen.getByLabelText('Tipo de movimiento'), 'adjustment_out')
    await waitFor(() => expect(screen.getByLabelText('Cantidad equivalente')).toHaveValue('0.750000'))
    expect(screen.getByRole('button', { name: 'Confirmar movimiento' })).toBeDisabled()
    await clicker.type(screen.getByLabelText('Justificación del ajuste'), 'Conteo físico')
    expect(screen.getByRole('button', { name: 'Confirmar movimiento' })).toBeEnabled()
  })
  it('retries an uncertain network result with the same UUID', async () => {
    inventoryService.confirm.mockRejectedValueOnce(new Error('network')).mockResolvedValue(movement)
    const clicker = userEvent.setup()
    await prepareMovement(clicker)
    await clicker.click(screen.getByRole('button', { name: 'Confirmar movimiento' }))
    await clicker.click(await screen.findByRole('button', { name: 'Reintentar confirmación' }))
    expect(await screen.findByText('LDR-DP-0001')).toBeInTheDocument()
    expect(inventoryService.confirm.mock.calls[0][0].idempotency_key).toBe(inventoryService.confirm.mock.calls[1][0].idempotency_key)
  })
  it('shows backend validation without a receipt', async () => {
    inventoryService.confirm.mockRejectedValue(httpError(422, { errors: { quantity_original: ['Existencia insuficiente al confirmar.'] } }))
    const clicker = userEvent.setup()
    await prepareMovement(clicker)
    await clicker.click(screen.getByRole('button', { name: 'Confirmar movimiento' }))
    expect(await screen.findByText('Existencia insuficiente al confirmar.')).toBeInTheDocument()
    expect(screen.queryByText('LDR-DP-0001')).not.toBeInTheDocument()
  })
  it('limits operational consumers to backend-authorized exit type', async () => {
    authService.currentUser.mockResolvedValue({ ...user, permissions: ['materials.view', 'materials.consume'] })
    inventoryService.meta.mockResolvedValue({ ...inventoryMeta, allowed_movement_types: inventoryMeta.movement_types.filter((type) => type.value === 'exit') })
    renderApp('/materials/movements/new')
    const select = await screen.findByLabelText('Tipo de movimiento')
    expect(within(select).getAllByRole('option')).toHaveLength(1)
    expect(select).toHaveValue('exit')
  })
  it('hides write actions for read-only users', async () => {
    authService.currentUser.mockResolvedValue({ ...user, permissions: ['materials.view'] })
    renderApp('/materials/movements')
    await screen.findByRole('table')
    expect(screen.queryByRole('link', { name: 'Registrar movimiento' })).not.toBeInTheDocument()
  })
  it.each(['/materials/movements', '/materials/movements/new', '/materials/movements/10', '/materials/inventory/dashboard'])('guards direct access to %s', async (path) => {
    authService.currentUser.mockResolvedValue({ ...user, permissions: [] })
    renderApp(path)
    expect(await screen.findByRole('heading', { name: 'Acceso denegado' })).toBeInTheDocument()
    expect(inventoryService.meta).not.toHaveBeenCalled()
  })
  it('consumes original units through the Work Order and displays its linked folio', async () => {
    const clicker = userEvent.setup()
    renderApp('/work-orders/15')
    await clicker.click(await screen.findByRole('button', { name: 'Registrar consumo' }))
    await screen.findByLabelText('Material')
    await clicker.selectOptions(screen.getByLabelText('Material'), '5')
    await clicker.type(screen.getByLabelText('Cantidad', { exact: true }), '750')
    await clicker.selectOptions(screen.getByLabelText('Unidad original del consumo'), 'ml')
    await waitFor(() => expect(screen.getByRole('button', { name: 'Guardar consumo' })).toBeEnabled())
    await clicker.click(screen.getByRole('button', { name: 'Guardar consumo' }))
    await waitFor(() => expect(operationsService.consume).toHaveBeenCalledWith(15, expect.objectContaining({ quantity: '750', unit_original: 'ml', work_order_process_step_id: 51, idempotency_key: expect.any(String) })))
    expect(await screen.findByText('LDR-DP-0001')).toBeInTheDocument()
  })
})
