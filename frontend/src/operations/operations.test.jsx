describe('inspection execution, rework and release', () => {
  it('lists inspections and supports search', async () => {
    const clicker = userEvent.setup()
    renderApp('/inspections')
    expect(await screen.findByRole('link', { name: 'Ver inspección 100' })).toHaveAttribute('href', '/inspections/100')
    await clicker.type(screen.getByLabelText('Buscar inspecciones'), 'RA123456')
    await clicker.click(screen.getByRole('button', { name: 'Buscar', exact: true }))
    await waitFor(() => expect(operationsService.inspections).toHaveBeenLastCalledWith({ search: 'RA123456' }, null, expect.anything()))
  })
  it('shows the empty inspection state', async () => {
    operationsService.inspections.mockResolvedValue(collection([]))
    renderApp('/inspections')
    expect(await screen.findByText('No hay inspecciones para mostrar.')).toBeInTheDocument()
  })
  it('creates inspection as Inspector using completed-order lookup without Work Order view', async () => {
    authService.currentUser.mockResolvedValue({ ...user, roles: ['inspector'], permissions: ['inspection.view','inspection.execute','release.execute'] })
    operationsService.createInspection.mockResolvedValue(inspection)
    const clicker = userEvent.setup()
    renderApp('/inspections/new')
    await clicker.selectOptions(await screen.findByLabelText('Orden completada', { selector: 'select' }), '15')
    await clicker.selectOptions(await screen.findByLabelText('Checklist', { selector: 'select' }), '9')
    await clicker.click(screen.getByRole('button', { name: 'Crear inspección' }))
    await waitFor(() => expect(operationsService.createInspection).toHaveBeenCalledWith(15, { inspection_checklist_id: 9, notes: null }))
    expect(await screen.findByRole('heading', { name: 'Detalle de inspección' })).toBeInTheDocument()
    expect(workOrderService.get).not.toHaveBeenCalled()
  })
  it('shows VIN and model for creation within a Work Order', async () => {
    renderApp('/work-orders/15/inspections/new')
    expect(await screen.findByText(order.unit.vin)).toBeInTheDocument()
    expect(operationsService.eligibleOrders).toHaveBeenCalledWith({ work_order_id: '15' }, expect.anything())
  })
  it('handles rejected creation', async () => {
    operationsService.createInspection.mockRejectedValue(httpError(422, { errors: { inspection: ['Esta orden ya tiene una inspección en borrador.'] } }))
    const clicker = userEvent.setup()
    renderApp('/work-orders/15/inspections/new')
    await clicker.selectOptions(await screen.findByLabelText('Checklist', { selector: 'select' }), '9')
    await clicker.click(screen.getByRole('button', { name: 'Crear inspección' }))
    expect(await screen.findByText('Esta orden ya tiene una inspección en borrador.')).toBeInTheDocument()
  })
  it('blocks completion until required answers are provided and shows the summary', async () => {
    renderApp('/inspections/100')
    const button = await screen.findByRole('button', { name: 'Completar inspección' })
    expect(button).toBeDisabled()
    expect(screen.getByText('Cumple: 0 · No cumple: 0 · Pendiente: 2')).toBeInTheDocument()
  })
  it('saves answers with comments without client-controlled overall result', async () => {
    const clicker = userEvent.setup()
    renderApp('/inspections/100')
    await clicker.selectOptions(await screen.findByLabelText('Resultado: Superficie sin daño'), 'compliant')
    await clicker.type(screen.getByLabelText('Comentario: Superficie sin daño'), ' Correcto ')
    await clicker.click(screen.getByRole('button', { name: 'Guardar respuestas' }))
    await waitFor(() => expect(operationsService.saveInspection).toHaveBeenCalledWith(100, { notes: null, items: [
      { id: 191, result: 'compliant', comment: 'Correcto' }, { id: 192, result: null, comment: null },
    ] }))
  })
  it('requires a rework cause and renders automatically generated rework after failure', async () => {
    const clicker = userEvent.setup()
    renderApp('/inspections/100')
    await clicker.selectOptions(await screen.findByLabelText('Resultado: Superficie sin daño'), 'non_compliant')
    expect(screen.getByRole('button', { name: 'Completar inspección' })).toBeDisabled()
    await clicker.type(screen.getByLabelText('Causa de retrabajo'), 'Corregir pintura')
    operationsService.inspection.mockResolvedValue({ ...inspection, status: 'completed', status_label: 'Completada', result: 'failed', result_label: 'No cumple',
      unit: { ...inspection.unit, status: 'rework', status_label: 'Retrabajo' }, items: inspection.items.map((item, index) => ({ ...item, result: index === 0 ? 'non_compliant' : null, result_label: index === 0 ? 'No cumple' : null })),
      rework: { id: 20, cause: 'Corregir pintura', status: 'open', status_label: 'Abierto' } })
    await clicker.click(screen.getByRole('button', { name: 'Completar inspección' }))
    await waitFor(() => expect(operationsService.complete).toHaveBeenCalledWith(100, { rework_cause: 'Corregir pintura' }))
    expect(await screen.findByRole('heading', { name: 'Retrabajo generado automáticamente' })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Generar retrabajo' })).not.toBeInTheDocument()
  })
  it('handles completion validation from a changed server state', async () => {
    operationsService.complete.mockRejectedValue(httpError(422, { errors: { items: ['Responde todos los criterios obligatorios antes de completar.'] } }))
    const clicker = userEvent.setup()
    renderApp('/inspections/100')
    await clicker.selectOptions(await screen.findByLabelText('Resultado: Superficie sin daño'), 'compliant')
    await clicker.click(screen.getByRole('button', { name: 'Completar inspección' }))
    expect(await screen.findByText('Responde todos los criterios obligatorios antes de completar.')).toBeInTheDocument()
  })
  it('renders completed inspection read-only and validates release from backend checks', async () => {
    operationsService.inspection.mockResolvedValue({ ...inspection, status: 'completed', result: 'passed', result_label: 'Cumple', release_checks: { ...releaseChecks, no_open_rework: false } })
    renderApp('/inspections/100')
    expect(await screen.findByRole('button', { name: 'Liberar unidad' })).toBeDisabled()
    expect(screen.queryByRole('button', { name: 'Guardar respuestas' })).not.toBeInTheDocument()
    expect(screen.getByText('Sin retrabajos abiertos:')).toHaveTextContent('No cumple')
  })
  it('releases a valid passed inspection and displays the release actor and Unit state', async () => {
    operationsService.inspection.mockResolvedValue({ ...inspection, status: 'completed', result: 'passed', result_label: 'Cumple', release_checks: releaseChecks,
      unit: { ...inspection.unit, status: 'ready_for_release', status_label: 'Lista para liberar' } })
    const clicker = userEvent.setup()
    renderApp('/inspections/100')
    expect(await screen.findByText('Unidad lista para liberación.')).toBeInTheDocument()
    operationsService.inspection.mockResolvedValue({ ...inspection, status: 'completed', result: 'passed', result_label: 'Cumple', release_checks: { ...releaseChecks, not_released: false },
      unit: { ...inspection.unit, status: 'released', status_label: 'Liberada' }, release: { id: 30, released_by: { id: 7, name: user.name }, released_at: '2026-11-02T13:00:00Z' } })
    await clicker.click(screen.getByRole('button', { name: 'Liberar unidad' }))
    await waitFor(() => expect(operationsService.release).toHaveBeenCalledWith(100, { notes: null }))
    expect(await screen.findByRole('heading', { name: 'Unidad liberada' })).toBeInTheDocument()
    expect(screen.getByText('Liberada', { selector: 'dd' })).toBeInTheDocument()
  })
  it('hides execution and release controls for view-only users', async () => {
    authService.currentUser.mockResolvedValue({ ...user, permissions: ['inspection.view'] })
    renderApp('/inspections/100')
    await screen.findByText('Inspección #100 · Borrador')
    expect(screen.queryByRole('button', { name: 'Guardar respuestas' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Liberar unidad' })).not.toBeInTheDocument()
  })
  it.each([403,404])('handles inspection error %i', async (status) => {
    operationsService.inspection.mockRejectedValue(httpError(status))
    renderApp('/inspections/100')
    expect(await screen.findByRole('alert')).toHaveTextContent(status === 403 ? 'No tienes permiso' : 'Registro no encontrado')
  })
})
