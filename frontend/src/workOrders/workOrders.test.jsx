    authService.currentUser.mockResolvedValue({ ...user, permissions: ['work_orders.view', 'work_orders.assign'] })
    renderApp('/work-orders/15')
    expect(await screen.findByRole('button', { name: 'Guardar asignación' })).toBeInTheDocument()
