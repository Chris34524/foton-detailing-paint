function LocationProbe() { const location = useLocation(); return <span data-testid="location">{location.pathname + location.search}</span> }
function renderApp(path = '/work-orders') {
  return render(<MemoryRouter initialEntries={[path]}><AuthProvider><AppRoutes /><LocationProbe /></AuthProvider></MemoryRouter>)
}
