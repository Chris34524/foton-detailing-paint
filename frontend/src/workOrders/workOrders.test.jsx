    workOrderService.assign.mockRejectedValue(httpError(422, { errors: { assigned_to: ['Selecciona un usuario con rol de operador.'] } }))
    const clicker = userEvent.setup()
    renderApp('/work-orders/15')
    await clicker.selectOptions(await screen.findByLabelText('Operador asignado'), '24')
    await clicker.click(screen.getByRole('button', { name: 'Guardar asignación' }))
