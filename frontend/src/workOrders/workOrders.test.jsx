    workOrderService.get.mockResolvedValue({ ...order, status, is_terminal: true, allowed_status_transitions: [] })
    renderApp('/work-orders/15')
    expect(await screen.findByText('Orden finalizada · solo lectura.')).toBeInTheDocument()
